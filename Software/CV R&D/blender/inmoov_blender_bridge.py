from __future__ import annotations

"""Blender bridge v0.4: visualize the *real* InMoov IK solution via source FK.

This is intentionally a visualization adapter only. It does not recalculate IK.
The CV/IK process remains authoritative and sends `joint_names` +
`joint_angles_rad`; this bridge applies those same solved angles to the source
URDF bones that the builder aligned to each published joint axis.

Use a model generated by the current `builder/build_inmoov_complete.py`.
Legacy proxy-bound blends should be rebuilt with that builder. v0.3 consumes
the separate simulation-motion tree when present;
the authoritative CV/IK targets remain untouched in frame["robot"].
"""

import json
import socket
import time
import traceback
import bpy

ARMATURE_NAME = "InMoov_AnimationRig"
HOST = "127.0.0.1"
PORT = 8765
POLL_SECONDS = 0.01
STALE_AFTER_SECONDS = 1.0
APPLY_LEGS = False

# Visualization-only coordinate correction.
#
# The camera/CV coordinate frame is horizontally mirrored relative to the
# Blender rig on several user-facing axes.  Do NOT apply these signs to
# frame["robot"] or to future real actuator commands; they are only for this
# visualization adapter.  Arm IK joint angles and finger curls remain
# untouched because their source-FK mapping is already correct.
VISUAL_AXIS_SIGN = {
    "torso_yaw": -1.0,
    "torso_bend": -1.0,
    "head_turn": -1.0,
    "head_nod": 1.0,
    "head_tilt": -1.0,
    "jaw": 1.0,
    "left_eye_pan": -1.0,
    "left_eye_tilt": 1.0,
    "right_eye_pan": -1.0,
    "right_eye_tilt": 1.0,
    "left_wrist_rotation": -1.0,
    "left_wrist_bend": 1.0,
    "right_wrist_rotation": -1.0,
    "right_wrist_bend": 1.0,
}

_SOCKET = None
_RUNNING = False
_PACKET_COUNT = 0
_LAST_PACKET_WALL = 0.0
_SOURCE_JOINT_BONES = {}
_SOURCE_LINK_BONES = {}

CONTROL = {
    "torso_yaw": "CTRL_TORSO_YAW",
    "torso_bend": "CTRL_TORSO_BEND",
    "head_turn": "CTRL_HEAD_TURN",
    "head_nod": "CTRL_HEAD_NOD",
    "head_tilt": "CTRL_HEAD_TILT",
    "jaw": "CTRL_JAW",
    "left_eye_pan": "CTRL_EYE.L.PAN",
    "left_eye_tilt": "CTRL_EYE.L.TILT",
    "right_eye_pan": "CTRL_EYE.R.PAN",
    "right_eye_tilt": "CTRL_EYE.R.TILT",
}

FINGER_LINK_SUFFIXES = {
    "thumb": ("thumb_link", "thumb3_link"),
    "index": ("index_link", "index2_link", "index3_link"),
    "middle": ("majeure_link", "majeure2_link", "majeure3_link"),
    "ring": ("ringfinger_link", "ringfinger2_link", "ringfinger3_link"),
    "pinky": ("pinky_link", "pinky2_link", "pinky3_link"),
}


def _rig():
    obj = bpy.data.objects.get(ARMATURE_NAME)
    if obj is None or obj.type != "ARMATURE":
        raise RuntimeError(f"Armature {ARMATURE_NAME!r} not found")
    return obj


def _pose_bone(rig, name):
    bone = rig.pose.bones.get(name)
    if bone is None:
        raise RuntimeError(f"Required pose bone missing: {name}")
    return bone


def _safe_prop_name(name):
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in name)


def _visual_angle(key: str, angle: float) -> float:
    return float(VISUAL_AXIS_SIGN.get(key, 1.0)) * float(angle)


def _set_y_rotation(rig, name, angle):
    pb = _pose_bone(rig, name)
    pb.rotation_mode = "XYZ"
    pb.rotation_euler.y = float(angle)


def _canonical_joint_name(name: str) -> str:
    n = str(name).strip().lower()
    if n.startswith("src::"):
        n = n[5:]
    for suffix in ("_link_joint", "_joint", "_link"):
        if n.endswith(suffix):
            n = n[: -len(suffix)]
            break
    return n


def _build_source_maps(rig):
    _SOURCE_JOINT_BONES.clear()
    _SOURCE_LINK_BONES.clear()
    for pb in rig.pose.bones:
        link = pb.get("urdf_link")
        joint = pb.get("urdf_joint_name")
        if link:
            _SOURCE_LINK_BONES[str(link).lower()] = pb.name
        if joint:
            _SOURCE_JOINT_BONES[_canonical_joint_name(str(joint))] = pb.name


def _set_source_joint(rig, joint_name: str, angle: float) -> bool:
    bone_name = _SOURCE_JOINT_BONES.get(_canonical_joint_name(joint_name))
    if not bone_name:
        return False
    pb = rig.pose.bones.get(bone_name)
    if pb is None:
        return False
    # Builder v3.9 aligns source-bone local Y to the URDF joint axis.
    pb.rotation_mode = "XYZ"
    pb.rotation_euler.y = float(angle)
    return True


def _finger_angle_from_curl(pb, curl: float) -> float:
    curl = max(0.0, min(1.0, float(curl)))
    # Prefer the actual builder-created URDF limit constraint, preserving the
    # source model's mechanical range instead of inventing a Blender-only one.
    lo = 0.0
    hi = 1.57079632679
    for con in pb.constraints:
        if con.type == "LIMIT_ROTATION" and getattr(con, "use_limit_y", False):
            lo = float(con.min_y)
            hi = float(con.max_y)
            break
    # Open hand is zero when zero is inside the legal interval. Curl toward the
    # legal endpoint with greatest positive flexion. Current InMoov finger joints
    # are 0..pi/2, but this remains safe for modest future limit changes.
    open_angle = min(max(0.0, lo), hi)
    closed_angle = hi if abs(hi - open_angle) >= abs(lo - open_angle) else lo
    return open_angle + (closed_angle - open_angle) * curl



def _apply_cogley_face(face):
    """Retarget MediaPipe facial signals to Cogley's original 0..1 rig controls.

    Cogley head is parented to original HEAD_TURN bone. Neck orientation is
    controlled by original source-FK bones; the duplicate Cogley head rotation
    properties remain at their neutral 0.5 to avoid double head movement.
    """
    cogley = bpy.data.objects.get("COGLY_HEAD_RIG")
    if cogley is None or cogley.type != 'ARMATURE':
        return
    import math
    def clip(x):return max(0.0, min(1.0, float(x)))
    def centered(angle, extent):
        return clip(.5 + float(angle)/(2.0*extent)) if extent else .5
    def setp(key, value):
        if key in cogley:
            cogley[key] = clip(value)
    eyes = face.get("eyes", {})
    for side in ('left','right'):
        eye = eyes.get(side,{})
        setp(f'eye_{side}_yaw', centered(_visual_angle(f'{side}_eye_pan', eye.get('pan_rad',0.0)), math.radians(28)))
        setp(f'eye_{side}_pitch',centered(_visual_angle(f'{side}_eye_tilt',eye.get('tilt_rad',0.0)),math.radians(20)))
    setp('mouth_open',float(face.get('jaw_rad',0.0))/math.radians(28))
    lids=face.get('eyelids',{})
    setp('blink_left',lids.get('left_closed',0.0))
    setp('blink_right',lids.get('right_closed',0.0))
    bs=face.get('expression_blendshapes',{}) or {}
    for side in ('left','right'):
        tag=side.title()
        smile=bs.get('mouthSmile'+tag,0.)
        frown=bs.get('mouthFrown'+tag,0.)
        brow_up=max(float(bs.get('browInnerUp',0.)),float(bs.get('browOuterUp'+tag,0.)))
        brow_down=float(bs.get('browDown'+tag,0.))
        setp(f'smile_{side}',.5+.5*(smile-frown))
        setp(f'brow_{side}',.5+.5*(brow_up-brow_down))
        setp(f'lip_upper_{side}',.5+.5*(float(bs.get('mouthUpperUp'+tag,0.))-float(bs.get('mouthPress'+tag,0.))))
        setp(f'lip_lower_{side}',.5+.5*(float(bs.get('mouthLowerDown'+tag,0.))-float(bs.get('mouthPress'+tag,0.))))
        setp(f'corner_{side}_x',.5+.5*(float(bs.get('mouthStretch'+tag,0.))-float(bs.get('mouthPucker',0.))))
        setp(f'corner_{side}_z',.5+.5*(smile-frown))
    cogley['CV_EXPRESSION_SOURCE']='MediaPipe blendshapes; heuristic normalized control mapping'
    cogley['CV_EXPRESSION_LIMITS']='Visual-only; not servo-calibrated physical articulation'


def _apply_body_and_face(rig, frame):
    robot = frame.get("simulation") or frame.get("robot", {})
    torso = robot.get("torso", {})
    if torso.get("valid"):
        raw_yaw = float(torso.get("yaw_rad", 0.0))
        raw_bend = float(torso.get("bend_rad", 0.0))
        applied_yaw = _visual_angle("torso_yaw", raw_yaw)
        applied_bend = _visual_angle("torso_bend", raw_bend)
        _set_y_rotation(rig, CONTROL["torso_yaw"], applied_yaw)
        _set_y_rotation(rig, CONTROL["torso_bend"], applied_bend)
        rig["CV_TORSO_YAW_DEG"] = raw_yaw * 57.29577951308232
        rig["CV_TORSO_BEND_DEG"] = raw_bend * 57.29577951308232
        rig["CV_SIM_TORSO_YAW_APPLIED_DEG"] = applied_yaw * 57.29577951308232
        rig["CV_SIM_TORSO_BEND_APPLIED_DEG"] = applied_bend * 57.29577951308232
        rig["CV_TORSO_SAGITTAL_LEAN_UNAPPLIED_DEG"] = float(torso.get("tracked_sagittal_lean_rad", 0.0)) * 57.29577951308232

    face = robot.get("face", {})
    if face.get("valid"):
        head = face.get("head", {})
        raw_head_turn = float(head.get("turn_rad", 0.0))
        raw_head_nod = float(head.get("nod_rad", 0.0))
        raw_head_tilt = float(head.get("tilt_rad", 0.0))
        raw_jaw = float(face.get("jaw_rad", 0.0))
        applied_head_turn = _visual_angle("head_turn", raw_head_turn)
        applied_head_nod = _visual_angle("head_nod", raw_head_nod)
        applied_head_tilt = _visual_angle("head_tilt", raw_head_tilt)
        applied_jaw = _visual_angle("jaw", raw_jaw)
        _set_y_rotation(rig, CONTROL["head_turn"], applied_head_turn)
        _set_y_rotation(rig, CONTROL["head_nod"], applied_head_nod)
        _set_y_rotation(rig, CONTROL["head_tilt"], applied_head_tilt)
        _set_y_rotation(rig, CONTROL["jaw"], applied_jaw)
        rig["CV_SIM_HEAD_TURN_APPLIED_DEG"] = applied_head_turn * 57.29577951308232
        rig["CV_SIM_HEAD_NOD_APPLIED_DEG"] = applied_head_nod * 57.29577951308232
        rig["CV_SIM_HEAD_TILT_APPLIED_DEG"] = applied_head_tilt * 57.29577951308232

        eyes = face.get("eyes", {})
        left = eyes.get("left", {})
        right = eyes.get("right", {})
        _set_y_rotation(rig, CONTROL["left_eye_pan"], _visual_angle("left_eye_pan", left.get("pan_rad", 0.0)))
        _set_y_rotation(rig, CONTROL["left_eye_tilt"], _visual_angle("left_eye_tilt", left.get("tilt_rad", 0.0)))
        _set_y_rotation(rig, CONTROL["right_eye_pan"], _visual_angle("right_eye_pan", right.get("pan_rad", 0.0)))
        _set_y_rotation(rig, CONTROL["right_eye_tilt"], _visual_angle("right_eye_tilt", right.get("tilt_rad", 0.0)))
        rig["CV_EYE_LEFT_PAN_DEG"] = float(left.get("pan_rad", 0.0)) * 57.29577951308232
        rig["CV_EYE_LEFT_TILT_DEG"] = float(left.get("tilt_rad", 0.0)) * 57.29577951308232
        rig["CV_EYE_RIGHT_PAN_DEG"] = float(right.get("pan_rad", 0.0)) * 57.29577951308232
        rig["CV_EYE_RIGHT_TILT_DEG"] = float(right.get("tilt_rad", 0.0)) * 57.29577951308232
        rig["CV_EYE_TEST_ENABLED"] = bool(face.get("eye_test_enabled", False))

        eyelids = face.get("eyelids", {})
        rig["CV_EYELID_LEFT_CLOSED"] = float(eyelids.get("left_closed", 0.0))
        rig["CV_EYELID_RIGHT_CLOSED"] = float(eyelids.get("right_closed", 0.0))
        for name, value in face.get("expression_blendshapes", {}).items():
            rig[f"CV_BS_{_safe_prop_name(name)}"] = float(value)
        _apply_cogley_face(face)


def _apply_arm_source_fk(rig, frame):
    source = frame.get("simulation") or frame.get("robot", {})
    arms = source.get("arms", {})
    for side_label in ("left", "right"):
        command = arms.get(side_label, {})
        if not command.get("valid"):
            continue

        names = list(command.get("joint_names", []))
        angles = list(command.get("joint_angles_rad", []))
        missing = []
        for name, angle in zip(names, angles):
            if not _set_source_joint(rig, name, angle):
                missing.append(name)

        for idx, value in enumerate(angles):
            rig[f"CV_IK_{side_label.upper()}_Q{idx}_RAD"] = float(value)
        rig[f"CV_IK_{side_label.upper()}_WRIST_ERROR_MM"] = float(command.get("wrist_error_mm", 0.0))
        rig[f"CV_IK_{side_label.upper()}_ELBOW_ERROR_MM"] = float(command.get("elbow_error_mm", 0.0))
        rig[f"CV_IK_{side_label.upper()}_HIT_LIMIT"] = bool(command.get("hit_limit", False))
        rig[f"CV_SIM_{side_label.upper()}_MISSING_JOINTS"] = ",".join(missing)


def _apply_wrists_source_fk(rig, frame):
    source = frame.get("simulation") or frame.get("robot", {})
    hands = source.get("hands", {})
    for side_label in ("left", "right"):
        wrist = hands.get(side_label, {}).get("wrist", {})
        if not wrist.get("valid"):
            continue
        rotation_name = wrist.get("rotation_joint_name", f"{side_label}_wrist_z")
        bend_name = wrist.get("bend_joint_name", f"i01.{side_label}Hand.wrist.001")
        rotation = float(wrist.get("rotation_rad", 0.0))
        bend = float(wrist.get("bend_rad", 0.0))
        applied_rotation = _visual_angle(f"{side_label}_wrist_rotation", rotation)
        applied_bend = _visual_angle(f"{side_label}_wrist_bend", bend)
        ok_rotation = _set_source_joint(rig, rotation_name, applied_rotation)
        ok_bend = _set_source_joint(rig, bend_name, applied_bend)
        prefix = side_label.upper()
        rig[f"CV_WRIST_{prefix}_ROTATION_DEG"] = rotation * 57.29577951308232
        rig[f"CV_WRIST_{prefix}_BEND_DEG"] = bend * 57.29577951308232
        rig[f"CV_SIM_WRIST_{prefix}_ROTATION_APPLIED_DEG"] = applied_rotation * 57.29577951308232
        rig[f"CV_SIM_WRIST_{prefix}_BEND_APPLIED_DEG"] = applied_bend * 57.29577951308232
        rig[f"CV_WRIST_{prefix}_ROTATION_APPLIED"] = bool(ok_rotation)
        rig[f"CV_WRIST_{prefix}_BEND_APPLIED"] = bool(ok_bend)


def _apply_fingers_source_fk(rig, frame):
    source = frame.get("simulation") or frame.get("robot", {})
    hands = source.get("hands", {})
    for side_label in ("left", "right"):
        command = hands.get(side_label, {})
        if not command.get("valid"):
            continue
        side_token = f"i01.{side_label}hand."

        for finger_name, curl in command.get("curls", {}).items():
            suffixes = FINGER_LINK_SUFFIXES.get(str(finger_name).lower(), ())
            applied = 0
            for link_suffix in suffixes:
                wanted = (side_token + link_suffix).lower()
                bone_name = _SOURCE_LINK_BONES.get(wanted)
                if not bone_name:
                    continue
                pb = rig.pose.bones.get(bone_name)
                if pb is None:
                    continue
                pb.rotation_mode = "XYZ"
                pb.rotation_euler.y = _finger_angle_from_curl(pb, float(curl))
                applied += 1
            rig[f"CV_{side_label.upper()}_{str(finger_name).upper()}_CURL"] = float(curl)
            rig[f"CV_SIM_{side_label.upper()}_{str(finger_name).upper()}_JOINTS"] = applied


def _apply_tracking_diagnostics(rig, frame):
    tracking = frame.get("tracking", {})
    rig["CV_FACE_VALID"] = bool(tracking.get("face_valid", False))
    rig["CV_BODY_VALID"] = bool(tracking.get("body_valid", False))
    rig["CV_LEFT_HAND_VALID"] = bool(tracking.get("left_hand_valid", False))
    rig["CV_RIGHT_HAND_VALID"] = bool(tracking.get("right_hand_valid", False))
    for name, value in tracking.get("body_joint_metrics_rad", {}).items():
        rig[f"CV_BODY_{_safe_prop_name(name).upper()}_RAD"] = float(value)


def apply_frame(frame):
    global _LAST_PACKET_WALL, _PACKET_COUNT
    if frame.get("schema") not in {"inmoov.cv_ik.poc.v1", "inmoov.cv_ik.poc.v2"}:
        return

    rig = _rig()
    _apply_body_and_face(rig, frame)
    _apply_arm_source_fk(rig, frame)
    _apply_wrists_source_fk(rig, frame)
    _apply_fingers_source_fk(rig, frame)
    _apply_tracking_diagnostics(rig, frame)
    collision = (frame.get('simulation') or frame.get('robot', {})).get('collision', frame.get('collision', {}))
    rig['CV_COLLISION_BLOCKED'] = bool(collision.get('blocked', False))
    rig['CV_COLLISION_APPROXIMATE'] = True
    for side in ('left','right'):
        arm = (frame.get('simulation') or frame.get('robot', {})).get('arms', {}).get(side, {})
        rig[f'CV_{side.upper()}_IK_REJECTED'] = str(arm.get('tracking_rejected', ''))

    rig["CV_SIMULATION_ONLY"] = True
    rig["CV_SIM_BINDING_MODE"] = "SOURCE_URDF_FK_VISUAL_REMAP"
    rig["CV_SIM_ARM_INPUT"] = "servo-profiled visualization copy; authoritative raw IK remains in packet.robot"
    rig["CV_BRIDGE_PACKET_COUNT"] = int(_PACKET_COUNT + 1)
    rig["CV_BRIDGE_SOURCE_TIMESTAMP_S"] = float(frame.get("timestamp_s", 0.0))
    rig["CV_BRIDGE_ALIVE"] = True

    _PACKET_COUNT += 1
    _LAST_PACKET_WALL = time.monotonic()
    bpy.context.view_layer.update()


def _poll():
    if not _RUNNING:
        return None
    try:
        newest = None
        while True:
            try:
                data, _address = _SOCKET.recvfrom(65535)
            except BlockingIOError:
                break
            newest = data

        if newest is not None:
            frame = json.loads(newest.decode("utf-8"))
            apply_frame(frame)
            if _PACKET_COUNT % 300 == 0:
                print(f"[InMoovBridge v0.4] {_PACKET_COUNT} packets applied")

        rig = bpy.data.objects.get(ARMATURE_NAME)
        if rig is not None and _LAST_PACKET_WALL:
            stale = (time.monotonic() - _LAST_PACKET_WALL) > STALE_AFTER_SECONDS
            rig["CV_BRIDGE_ALIVE"] = not stale
    except Exception:
        traceback.print_exc()
    return POLL_SECONDS


def stop_bridge():
    global _RUNNING, _SOCKET
    _RUNNING = False
    if _SOCKET is not None:
        try:
            _SOCKET.close()
        except Exception:
            pass
        _SOCKET = None
    rig = bpy.data.objects.get(ARMATURE_NAME)
    if rig is not None:
        rig["CV_BRIDGE_ALIVE"] = False
    print("[InMoovBridge v0.4] stopped")


def start_bridge():
    global _RUNNING, _SOCKET, _PACKET_COUNT, _LAST_PACKET_WALL
    stop_bridge()
    rig = _rig()
    _build_source_maps(rig)

    if not rig.get("CV_SIM_BINDING_REPAIRED", False):
        print("[InMoovBridge v0.4] WARNING: this blend is not marked as source-FK repaired.")
        print("[InMoovBridge v0.4] Rebuild legacy proxy-bound blends with builder/build_inmoov_complete.py.")

    _PACKET_COUNT = 0
    _LAST_PACKET_WALL = 0.0
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.bind((HOST, PORT))
    sock.setblocking(False)
    _SOCKET = sock
    _RUNNING = True

    rig["CV_BRIDGE_PORT"] = PORT
    rig["CV_BRIDGE_ALIVE"] = False
    rig["CV_SIMULATION_ONLY"] = True
    rig["CV_SIM_BINDING_MODE"] = "SOURCE_URDF_FK_VISUAL_REMAP"

    bpy.app.timers.register(_poll, first_interval=POLL_SECONDS, persistent=True)
    print(f"[InMoovBridge v0.4] listening on udp://{HOST}:{PORT}")
    print(f"[InMoovBridge v0.4] source joint bones indexed: {len(_SOURCE_JOINT_BONES)}")
    print("[InMoovBridge v0.4] source-FK visualization; simulation profile is separate from authoritative raw IK.")
    print("[InMoovBridge v0.4] visual mirror correction enabled for head turn/tilt, torso yaw/bend, eye pan, and wrist rotation.")
    print("[InMoovBridge v0.4] legs remain disabled by design.")


start_bridge()
